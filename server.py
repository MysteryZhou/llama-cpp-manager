# ---------------------------------------------------------------- 工具函数

def bat_text(path):
    for enc in ("utf-8", "gbk", "latin-1"):
        try:
            with open(path, "r", encoding=enc) as f:
                return f.read()
        except UnicodeDecodeError:
            continue
    return ""

def parse_script(path):
    """从 bat 文件提取模型元信息（供前端展示 + 启动参数）"""
    text = bat_text(path)
    def val(flag):
        m = re.search(r"--%s\s+(\S+)" % flag, text, re.S)
        return m.group(1) if m else None
    model = val("model")
    size = None
    if model and os.path.exists(model):
        size = round(os.path.getsize(model) / 1e9, 1)
    return {
        "script": os.path.basename(path),
        "path":   path,
        "alias":  val("alias") or os.path.splitext(os.path.basename(path))[0].replace("run-", ""),
        "model_file": os.path.basename(model) if model else "",
        "model_path": model or "",
        "size_gb": size,
        "ctx": int(val("ctx-size") or 0),
        "cache_kv": val("cache-type-k") or "f16",
        "mtp": "draft-mtp" in text,
        "gpu_layers": val("n-gpu-layers") or "99",
        "auto": "auto-generated" in text,
    }

def list_models():
    models = []
    for p in sorted(glob.glob(os.path.join(SCRIPTS, "run-*.bat"))):
        try:
            models.append(parse_script(p))
        except Exception:
            continue
    return models

