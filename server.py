# 扫描的模型存放目录（可用 llama-manager.json 的 models_dir 或环境变量 LLAMA_MODELS_DIR 覆盖）
_MODELS_BASE = cfg_get("models_dir", r"G:\models")
MODEL_DIRS = [_MODELS_BASE, os.path.join(_MODELS_BASE, "gguf")]

DEFAULT_BAT = r"""@echo off
title llama-server: {alias} (port {port})
cd /d {llama_dir}
echo ==========================================
echo   {model}
echo   API:   http://localhost:{port}/v1
echo   Model: {alias}
echo ==========================================
llama-server.exe ^
  --model {model} ^
  --alias {alias} ^
  --port {port} ^
  --host 127.0.0.1 ^
  --ctx-size 8192 ^
  --flash-attn on ^
  --cache-type-k q4_0 ^
  --cache-type-v q4_0 ^
  --reasoning off ^
  --fit on ^
  --n-gpu-layers 99
echo.
echo Server stopped. Press any key to close.
pause >nul
rem auto-generated by llama-manager
"""

def auto_gen_script(gguf_path):
    """为没有对应启动脚本的 GGUF 自动生成默认 run-*.bat；返回脚本路径或 None"""
    base = os.path.splitext(os.path.basename(gguf_path))[0].lower().replace(" ", "-")
    script = os.path.join(SCRIPTS, "run-%s.bat" % base)
    if os.path.exists(script):
        return None
    content = DEFAULT_BAT.format(alias=base, model=gguf_path,
                                 port=PORT_LLM, llama_dir=LLAMA_DIR)
    try:
        with open(script, "w", encoding="gbk", newline="\r\n") as f:
            f.write(content)
        return script
    except Exception:
        return None

def rewrite_bat_model(bat_path, new_model_path):
    """重写 bat 里的 --model 路径（用于修复移动后的模型）"""
    text = bat_text(bat_path)
    # 用 lambda 按字面替换，避免路径反斜杠被当作转义序列
    new_text = re.sub(r"(--model\s+)\S+",
                      lambda m: m.group(1) + new_model_path, text)
    if new_text == text:
        return False
    try:
        with open(bat_path, "w", encoding="gbk", newline="\r\n") as f:
            f.write(new_text)
        return True
    except Exception:
        return False

def sync_scripts():
    """扫描模型目录：
    1) 修复 bat 中失效的 --model 路径（文件被移动/改名后）
    2) 为新 GGUF 自动生成启动脚本
    返回 (added, repaired)"""
    added, repaired = [], []
    models = list_models()
    known = set()
    for m in models:
        if m["model_path"]:
            known.add(os.path.normcase(os.path.normpath(m["model_path"])))
    # 1) 修复失效路径
    for m in models:
        if not m["model_path"] or os.path.exists(m["model_path"]):
            continue
        fname = os.path.basename(m["model_path"])
        for d in MODEL_DIRS:
            cand = os.path.join(d, fname)
            if os.path.isfile(cand):
                if rewrite_bat_model(m["path"], cand):
                    repaired.append(m["script"])
                break
    # 2) 新增模型
    for d in MODEL_DIRS:
        if not os.path.isdir(d):
            continue
        for g in glob.glob(os.path.join(d, "*.gguf")):
            if os.path.normcase(os.path.normpath(g)) not in known:
                s = auto_gen_script(g)
                if s:
                    added.append(s)
    return added, repaired

def extract_args(bat_path):
    """从 bat 中提取 llama-server.exe 之后的命令行参数（处理 ^ 续行）"""
    text = re.sub(r"\^\s*\r?\n", " ", bat_text(bat_path))
    tokens = text.split()
    try:
        start = tokens.index("llama-server.exe") + 1
    except ValueError:
        start = 0
    args, i = [], start
    while i < len(tokens):
        t = tokens[i]
        if t.startswith("--"):
            args.append(t)
            if i + 1 < len(tokens) and not tokens[i + 1].startswith("--"):
                args.append(tokens[i + 1])
                i += 1
        i += 1
    return args

def build_args(bat_path, opts=None):
    """基于 bat 参数，按前端设置覆盖/增删参数"""
    args = extract_args(bat_path)
    opts = opts or {}
    d, i = {}, 0
    while i < len(args):
        flag = args[i]
        if i + 1 < len(args) and not args[i + 1].startswith("--"):
            d[flag] = args[i + 1]; i += 2
        else:
            d[flag] = True; i += 1
    def set_val(flag, val):
        if val is None or val == "":
            d.pop(flag, None)
        else:
            d[flag] = str(val)
    if "ctx" in opts:        set_val("--ctx-size", opts.get("ctx"))
    if "cache_k" in opts:    set_val("--cache-type-k", opts.get("cache_k"))
    if "cache_v" in opts:    set_val("--cache-type-v", opts.get("cache_v"))
    if "gpu_layers" in opts: set_val("--n-gpu-layers", opts.get("gpu_layers"))
    if "reasoning" in opts:
        set_val("--reasoning", "on" if opts.get("reasoning") else "off")
    if "flash_attn" in opts:
        set_val("--flash-attn", "on" if opts.get("flash_attn") else "off")
    if "parallel" in opts:      set_val("--parallel", opts.get("parallel"))
    if "threads" in opts:       set_val("--threads", opts.get("threads"))
    if "temp" in opts:          set_val("--temp", opts.get("temp"))
    if "top_p" in opts:         set_val("--top-p", opts.get("top_p"))
    if "repeat_penalty" in opts: set_val("--repeat-penalty", opts.get("repeat_penalty"))
    if "seed" in opts:          set_val("--seed", opts.get("seed"))
    mtp = opts.get("mtp")
    if mtp is not None:
        if mtp:
            d["--spec-type"] = "draft-mtp"
            d["--spec-draft-n-max"] = str(opts.get("mtp_n", 2))
        else:
            d.pop("--spec-type", None)
            d.pop("--spec-draft-n-max", None)
    out = []
    for k, v in d.items():
        out.append(k)
        if v is not True:
            out.append(v)
    return out

